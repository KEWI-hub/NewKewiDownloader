def groove(t0, t1, kick_pat="four", hats=True, open_hats=True, clap_on=True, energy=1.0, skip=None):
    for b in bars(t0, t1):
        for s in range(16):
            tt = b * BAR + s * S16
            if tt < t0 - 1e-6 or tt >= t1 - 1e-6:
                continue
            if skip and skip(tt):
                continue
            beat, sub = divmod(s, 4)
            if kick_pat == "four" and sub == 0:
                drums.add(tt, kick(1.0), 0.8 * energy)
            elif kick_pat == "half" and s in (0, 10):
                drums.add(tt, kick(1.0), 0.95 * energy)
            elif kick_pat == "break" and s in (0, 6, 10):
                drums.add(tt, kick(0.9), 0.85 * energy)
            if clap_on and sub == 0 and beat in (1, 3):
                drums.add(tt, clap(), 0.75 * energy, p=0.05)
                drums.add(tt, snare(0.3), 0.3 * energy)
            if hats:
                acc = 1.0 if sub == 2 else 0.55 if sub == 0 else 0.4
                drums.add(tt, hat(), 0.55 * acc * energy, p=0.3)
            if open_hats and sub == 2 and beat % 2 == 1:
                drums.add(tt, hat(True), 0.28 * energy, p=-0.3)


def bassline(t0, t1, pattern="eighths", gain=0.55, prog=PROG, skip=None):
    for b in bars(t0, t1):
        c = prog[b % len(prog)]
        r = ROOT[c]
        steps = [0, 2, 3, 4, 6, 7, 8, 10, 11, 12, 14, 15] if pattern == "drive" else list(range(0, 16, 2))
        for s in steps:
            tt = b * BAR + s * S16
            if tt < t0 - 1e-6 or tt >= t1 - 1e-6 or (skip and skip(tt)):
                continue
            m = r + (12 if (pattern == "drive" and s in (3, 7, 11, 15)) else 0)
            bass.add(tt, sub_note(m, S16 * 1.8), gain)


