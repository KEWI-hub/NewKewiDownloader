def compress(x, thr_db=-16, ratio=2.2, att=0.01, rel=0.18):
    m = np.sqrt(filt((x[0] ** 2 + x[1] ** 2) / 2, "lp", 12, 1).clip(1e-12))
    lvl = 20 * np.log10(m)
    over = np.maximum(0, lvl - thr_db)
    gr = -over * (1 - 1 / ratio)
    # smooth gain
    g = 10 ** (gr / 20)
    a = np.exp(-1 / (att * SR))
    r = np.exp(-1 / (rel * SR))
    out = np.empty_like(g)
    y = 1.0
    gg = g[::64]
    sm = np.empty_like(gg)
    for k in range(len(gg)):
        coef = a ** 64 if gg[k] < y else r ** 64
        y = coef * y + (1 - coef) * gg[k]
        sm[k] = y
    out = np.repeat(sm, 64)[: len(g)]
    return x * out


def limiter(x, ceil=0.89, look=0.004):
    L = int(look * SR)
    peak = np.max(np.abs(x), axis=0)
    from scipy.ndimage import maximum_filter1d, uniform_filter1d
    pk = maximum_filter1d(peak, size=2 * L + 1)
    g = np.minimum(1.0, ceil / np.maximum(pk, 1e-9))
    g = uniform_filter1d(g, size=L)
    g = np.minimum(g, ceil / np.maximum(pk, 1e-9) + 0.0)
    return x * g


