def write_wav(path, x):
    import wave
    y = np.clip(x, -1, 1)
    pcm = (y.T * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


