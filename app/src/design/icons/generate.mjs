// Generates every icon artefact from icons.source.mjs.
//   node app/src/design/icons/generate.mjs
// Outputs:
//   app/src/design/icons/svg/<name>.svg   standalone SVGs (currentColor)
//   app/src/design/icons/names.ts         IconName union + groups
//   app/src/design/icons/index.tsx        <Icon name="…" /> React component
//   design/assets/icons.js                plain-JS helper for the HTML mockups
import { writeFileSync, mkdirSync, readdirSync, unlinkSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { groups, icons } from "./icons.source.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../../..");
const svgDir = join(here, "svg");
mkdirSync(svgDir, { recursive: true });
for (const f of readdirSync(svgDir)) if (f.endsWith(".svg")) unlinkSync(join(svgDir, f));

const attrs = (o) =>
  Object.entries(o)
    .map(([k, v]) => `${k}="${v}"`)
    .join(" ");
const inner = (nodes) => nodes.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join("");
const SVG_OPEN =
  '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">';

const names = Object.keys(icons).sort();

// 1. SVG files
for (const name of names) {
  writeFileSync(join(svgDir, `${name}.svg`), `${SVG_OPEN}${inner(icons[name])}</svg>\n`);
}

// 2. names.ts
const groupEntries = Object.entries(groups)
  .map(([g, set]) => `  ${g}: [${Object.keys(set).map((n) => JSON.stringify(n)).join(", ")}],`)
  .join("\n");
writeFileSync(
  join(here, "names.ts"),
  `// AUTO-GENERATED by generate.mjs — do not edit. Source: icons.source.mjs
export const ICON_NAMES = [
${names.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
] as const;

export type IconName = (typeof ICON_NAMES)[number];

export const ICON_GROUPS = {
${groupEntries}
} as const satisfies Record<string, readonly IconName[]>;

export function isIconName(value: string): value is IconName {
  return (ICON_NAMES as readonly string[]).includes(value);
}
`
);

// 3. index.tsx
const camel = (k) => k.replace(/-([a-z])/g, (_, ch) => ch.toUpperCase());
const nodeLiteral = ([tag, a]) =>
  `[${JSON.stringify(tag)}, {${Object.entries(a)
    .map(([k, v]) => `${JSON.stringify(camel(k))}: ${typeof v === "number" ? v : JSON.stringify(v)}`)
    .join(", ")}}]`;
const map = names.map((n) => `  ${JSON.stringify(n)}: [${icons[n].map(nodeLiteral).join(", ")}],`).join("\n");

writeFileSync(
  join(here, "index.tsx"),
  `// AUTO-GENERATED by generate.mjs — do not edit. Source: icons.source.mjs
// Prism icon set: 24×24 grid, 1.75 stroke, round caps/joins, currentColor.
import { createElement, forwardRef, memo, useId, type SVGProps } from "react";
import type { IconName } from "./names";

export { ICON_NAMES, ICON_GROUPS, isIconName, type IconName } from "./names";

type IconNode = readonly [tag: "path" | "circle" | "rect" | "ellipse", props: Readonly<Record<string, string | number>>];

/** Raw geometry, exported for canvas/tray rendering or tests. */
export const ICONS: Readonly<Record<IconName, readonly IconNode[]>> = {
${map}
};

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "name" | "ref" | "children"> {
  /** Icon to render. */
  name: IconName;
  /** Rendered size in px (width = height). Default 18 (toolbar); use 16 in rows/menus, 14 in badges. */
  size?: number | string;
  /** Stroke width in 24-grid units. Default 1.75. Use 1.5 at ≥ 24 px, 2 at ≤ 14 px for optical balance. */
  strokeWidth?: number;
  /** Accessible label. When omitted the icon is decorative (aria-hidden). */
  title?: string;
}

/**
 * <Icon name="pause" />                       decorative, 18 px
 * <Icon name="status-error" size={14} />      inline status glyph
 * <Icon name="delete" title="Delete" />       standalone, announced as an image
 */
export const Icon = memo(
  forwardRef<SVGSVGElement, IconProps>(function Icon(
    { name, size = 18, strokeWidth = 1.75, title, className, ...rest },
    ref
  ) {
    const titleId = useId();
    const nodes = ICONS[name];
    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        focusable="false"
        className={className ? \`icon \${className}\` : "icon"}
        aria-hidden={title ? undefined : true}
        role={title ? "img" : undefined}
        aria-labelledby={title ? titleId : undefined}
        data-icon={name}
        {...rest}
      >
        {title ? <title id={titleId}>{title}</title> : null}
        {nodes ? nodes.map(([tag, props], i) => createElement(tag, { key: i, ...props })) : null}
      </svg>
    );
  })
);

export default Icon;
`
);

// 4. design/assets/icons.js (for mockups / specimen)
const jsMap = Object.fromEntries(names.map((n) => [n, inner(icons[n])]));
mkdirSync(join(repo, "design/assets"), { recursive: true });
writeFileSync(
  join(repo, "design/assets/icons.js"),
  `// AUTO-GENERATED by app/src/design/icons/generate.mjs — do not edit.
window.PRISM_ICON_GROUPS = ${JSON.stringify(Object.fromEntries(Object.entries(groups).map(([g, s]) => [g, Object.keys(s)])))};
window.PRISM_ICONS = ${JSON.stringify(jsMap)};
window.icon = function (name, size, cls, sw) {
  var body = window.PRISM_ICONS[name];
  if (body == null) { console.warn("missing icon", name); body = ""; }
  size = size || 18;
  return '<svg class="icon' + (cls ? " " + cls : "") + '" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + (sw || 1.75) + '" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + body + "</svg>";
};
`
);

console.log(`generated ${names.length} icons`);
